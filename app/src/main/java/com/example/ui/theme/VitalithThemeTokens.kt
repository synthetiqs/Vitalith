@Immutable
data class VitalithThemeTokens(
  val key: String,
  val label: String,
  val isDark: Boolean,
  val bgPage: Color,
  val bgSurface: Color,
  val bgCard: Color,
  val bgElevated: Color,
  val bgInput: Color,
  val bgNav: Color,
  val heroGradientStart: Color,
  val heroGradientEnd: Color,
  val heroBorder: Color,
  val textPrimary: Color,
  val textSecondary: Color,
  val textMuted: Color,
  val textFaint: Color,
  val accent: Color,
  val accentBright: Color,
  val accentSoft: Color,
  val accentBorder: Color,
  val accentText: Color,
  val amber: Color,
  val deltaPositive: Color,
  val success: Color,
  val rangeBg: Color,
  val rangeNormal: Color,
  val rangeElevated: Color,
  val rangeCritical: Color,
  val spark1: Color,
  val spark2: Color,
  val nodeTeal: Color,
  val nodeAmber: Color,
  val nodeCoral: Color,
  val navBg: Color,
  val navBorder: Color,
  val navActiveBg: Color,
  val navActiveColor: Color,
  val navIdle: Color,
  val chipBg: Color,
  val chipBorder: Color,
  val chipText: Color,
  val cardRadius: Dp = 24.dp,
  val borderWidthCard: Dp = 1.dp,
  val fontWeightDisplay: FontWeight = FontWeight.Bold
) {
  fun toColorScheme(): ColorScheme {
    return if (isDark) {
      darkColorScheme(
        primary = accentBright,
        onPrimary = bgPage,
        primaryContainer = accentSoft,
        onPrimaryContainer = accentText,
        secondary = accent,
        onSecondary = bgPage,
        background = bgPage,
        onBackground = textPrimary,
        surface = bgSurface,
        onSurface = textPrimary,
        surfaceVariant = bgCard,
        onSurfaceVariant = textSecondary,
        outline = navBorder,
        error = rangeCritical,
        errorContainer = rangeCritical.copy(alpha = 0.2f),
        onErrorContainer = textPrimary
      )
    } else {
      lightColorScheme(
        primary = accent,
        onPrimary = Color.White,
        primaryContainer = accentSoft,
        onPrimaryContainer = accentText,
        secondary = textSecondary,
        onSecondary = Color.White,
        background = bgPage,
        onBackground = textPrimary,
        surface = bgSurface,
        onSurface = textPrimary,
        surfaceVariant = bgCard,
        onSurfaceVariant = textSecondary,
        outline = navBorder,
        error = rangeCritical,
        errorContainer = rangeCritical.copy(alpha = 0.15f),
        onErrorContainer = rangeCritical
      )
    }
  }
}

